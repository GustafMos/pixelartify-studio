/**
 * Generates a 64x64 void-and-cluster blue-noise threshold matrix and embeds it
 * as base64 in src/core/blueNoiseData.ts. Run with: node scripts/generate-blue-noise.mjs
 *
 * Implements Ulichney's void-and-cluster method (1993) with periodic boundary
 * conditions and an incremental Gaussian energy field.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const SIZE = 64;
const N = SIZE * SIZE;
const SIGMA = 1.7;
const RADIUS = Math.ceil(SIGMA * 3);
const INITIAL_FRACTION = 0.1;

function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// Precompute wrapped Gaussian kernel offsets/weights.
const kernel = [];
let weightSum = 0;
for (let dy = -RADIUS; dy <= RADIUS; dy++) {
  for (let dx = -RADIUS; dx <= RADIUS; dx++) {
    const d2 = dx * dx + dy * dy;
    const w = Math.exp(-d2 / (2 * SIGMA * SIGMA));
    kernel.push({ dx, dy, w });
    weightSum += w;
  }
}
for (const k of kernel) k.w /= weightSum;

const on = new Uint8Array(N);
const energy = new Float32Array(N);

function wrapped(x, y) {
  return ((y + SIZE) % SIZE) * SIZE + ((x + SIZE) % SIZE);
}

function toggle(index, add) {
  const x = index % SIZE;
  const y = (index / SIZE) | 0;
  for (const k of kernel) {
    energy[wrapped(x + k.dx, y + k.dy)] += add * k.w;
  }
}

function tightestCluster() {
  let best = -1;
  let bestEnergy = -Infinity;
  for (let i = 0; i < N; i++) {
    if (on[i] && energy[i] > bestEnergy) {
      bestEnergy = energy[i];
      best = i;
    }
  }
  return best;
}

function largestVoid() {
  let best = -1;
  let bestEnergy = Infinity;
  for (let i = 0; i < N; i++) {
    if (!on[i] && energy[i] < bestEnergy) {
      bestEnergy = energy[i];
      best = i;
    }
  }
  return best;
}

const rng = mulberry32(0x9e3779b9);
const initialCount = Math.round(N * INITIAL_FRACTION);
const chosen = new Set();
while (chosen.size < initialCount) chosen.add(Math.floor(rng() * N));
for (const i of chosen) {
  on[i] = 1;
  toggle(i, 1);
}

// Relax the initial pattern.
for (let iter = 0; iter < 24; iter++) {
  const cluster = tightestCluster();
  on[cluster] = 0;
  toggle(cluster, -1);
  const v = largestVoid();
  if (v === cluster || on[v]) {
    on[cluster] = 1;
    toggle(cluster, 1);
    break;
  }
  on[v] = 1;
  toggle(v, 1);
}

// Rank assignment.
const rank = new Int32Array(N).fill(-1);
let count = 0;
for (let i = 0; i < N; i++) if (on[i]) count++;

let remaining = count;
while (remaining > 0) {
  const c = tightestCluster();
  on[c] = 0;
  toggle(c, -1);
  rank[c] = remaining - 1;
  remaining--;
}

for (let r = count; r < N; r++) {
  const v = largestVoid();
  on[v] = 1;
  toggle(v, 1);
  rank[v] = r;
}

const bytes = Buffer.alloc(N);
for (let i = 0; i < N; i++) {
  bytes[i] = Math.max(0, Math.min(255, Math.floor(((rank[i] + 0.5) / N) * 256)));
}

const b64 = bytes.toString('base64');
const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'src', 'core', 'blueNoiseData.ts');
writeFileSync(
  out,
  `/** Generated by scripts/generate-blue-noise.mjs — 64x64 void-and-cluster blue noise. */\nexport const BLUE_NOISE_B64 =\n  '${b64}';\n`,
  'utf8',
);

console.log(`Wrote ${out} (${b64.length} base64 chars)`);
console.log(`min=${Math.min(...bytes)} max=${Math.max(...bytes)} unique=${new Set(bytes).size}`);
